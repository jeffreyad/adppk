test_that("ISO 3166 Alpha 3 Numeric Codes Test", {
  # Sort the tibble based on the ISO alpha 3 code
  iso_alpha3_sorted <- iso_alpha3 %>%
    arrange(country)
  
  # Test for each country
  for (i in seq_len(nrow(iso_alpha3_sorted))) {
    expect_equal(
      iso_alpha3_sorted$numeric_code[i], 
      iso3166a3_numeric_decode[iso_alpha3_sorted$country[i]], 
      sprintf("Numeric code for %s should be %d", 
              iso_alpha3_sorted$country_long_name[i], 
              iso_alpha3_sorted$numeric_code[i])
    )
  }
})
